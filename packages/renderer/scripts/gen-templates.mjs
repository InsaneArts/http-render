// Turns templates/*.html into src/templates.ts so every tool (tsup, Vite, tsx, Vitest) loads them the same way.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../templates/", import.meta.url);
const entries = readdirSync(dir)
  .filter((f) => f.endsWith(".html"))
  .sort()
  .map((f) => `  ${f.replace(/\.html$/, "")}: ${JSON.stringify(readFileSync(new URL(f, dir), "utf8"))},`);

writeFileSync(
  new URL("../src/templates.ts", import.meta.url),
  `// Generated by scripts/gen-templates.mjs from templates/*.html. Do not edit.\nexport const templates = {\n${entries.join("\n")}\n} as const;\n`,
);
